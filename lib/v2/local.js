'use strict';

/*
 * Local tests: hand-made tests (and other paths) that survive a re-scaffold.
 * docs/specs/2026-11-15-local-tests-design.md, in the new layout:
 *
 *   scripts/local-tests.txt        the list (user-owned, never written here)
 *   micro-os-plus-iii/tests/platforms/<p>/tests/<name>/      a local test
 *   micro-os-plus-iii/tests/platforms/<p>/tests/tests.local.cmake
 *                                  its CMake wiring, through *_local hooks
 *
 * The scaffolder sets the listed paths aside before it copies anything and
 * puts them back after the copy, the pruning and the options; run.sh reads
 * the list at run time.
 */

const fs = require('node:fs');
const path = require('node:path');

const { ensureDir, isDirectory, isFile, readJson, writeFile, writeJson } = require('../util');
const { KERNEL_DIR } = require('./discover');

const LIST = 'scripts/local-tests.txt';
const STASH = '.scaffold-local-stash';
const MARK = 'micro-os-scaffold local tests';
const HOOK_FILE = 'tests.local.cmake';
const STARTERS = ['mtp-example', 'mtp-args', 'mtp-smp', 'mtp-eth-net', 'mtp-stdcpp'];
const GENERATED = [
  'run.sh',
  'scripts/env.sh',
  'scaffold.json',
  'README.md',
  'build-logs',
  `${KERNEL_DIR}/tests/mtp`,
  `${KERNEL_DIR}/tests/build`,
  'third_party/micro-test-plus',
  'third_party/stateos-stdc++',
  STASH,
];
const PLATFORMS = `${KERNEL_DIR}/tests/platforms`;

function read(file) {
  return isFile(file) ? fs.readFileSync(file, 'utf8') : '';
}

/** Parse scripts/local-tests.txt. Returns { tests, keep, errors, warnings }. */
function parseList(text) {
  const tests = [];
  const keep = [];
  const errors = [];
  text.split('\n').forEach((raw, index) => {
    const line = raw.replace(/#.*$/, '').trim();
    if (!line) return;
    const where = `${LIST}:${index + 1}`;
    const words = line.split(/\s+/);
    if (words[0] === 'keep') {
      if (words.length !== 2) errors.push(`${where}: keep takes one path`);
      else keep.push(words[1]);
      return;
    }
    if (words.length !== 1) {
      errors.push(`${where}: one test name per line ('${line}')`);
      return;
    }
    const [platform, name] = words[0].includes('/') ? words[0].split('/', 2) : [null, words[0]];
    if (!/^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(name)) errors.push(`${where}: '${name}' is not a test folder name`);
    else tests.push({ platform, name });
  });
  return { tests, keep, errors, warnings: [] };
}

function normalizeKeep(item, errors) {
  if (path.isAbsolute(item)) {
    errors.push(`keep ${item}: an absolute path (paths are relative to the workspace)`);
    return null;
  }
  const norm = path.posix.normalize(item.replaceAll('\\', '/')).replace(/\/$/, '');
  if (norm === '.' || norm.startsWith('../') || norm === '..') {
    errors.push(`keep ${item}: outside the workspace`);
    return null;
  }
  for (const generated of GENERATED) {
    if (norm === generated || norm.startsWith(`${generated}/`) || generated.startsWith(`${norm}/`)) {
      errors.push(`keep ${item}: ${generated} is generated by every scaffold run`);
      return null;
    }
  }
  return norm;
}

/** The list, validated against the destination. Throws on an error. */
function loadList(destination, log) {
  const file = path.join(destination, LIST);
  if (!isFile(file)) return null;
  const list = parseList(read(file));
  for (const test of list.tests) {
    if (STARTERS.includes(test.name)) list.errors.push(`${test.name}: a generated starter test, not a local one`);
  }
  list.keep = list.keep.map((k) => normalizeKeep(k, list.errors)).filter(Boolean);
  if (list.errors.length) {
    throw new Error(`${LIST}:\n  ${list.errors.join('\n  ')}`);
  }
  for (const k of list.keep) {
    if (k.startsWith(`${KERNEL_DIR}/`) || /^[a-z0-9]+\/micro-os-plus-iii-/.test(k)) {
      log(`  warning: kept local: ${k} -- source updates of this file are not applied`);
    }
  }
  return list;
}

/** The destination paths a list protects (relative), plus the hook files. */
function protectedPaths(destination, list) {
  const tests = [];
  const platformsDir = path.join(destination, PLATFORMS);
  const platforms = isDirectory(platformsDir) ? fs.readdirSync(platformsDir) : [];
  for (const test of list.tests) {
    const paths = platforms
      .filter((p) => !test.platform || test.platform === p)
      .map((p) => `${PLATFORMS}/${p}/tests/${test.name}`)
      .filter((rel) => isDirectory(path.join(destination, rel)));
    tests.push({ name: test.name, platform: test.platform, paths });
  }
  const hookFiles = platforms
    .map((p) => `${PLATFORMS}/${p}/tests/${HOOK_FILE}`)
    .filter((rel) => isFile(path.join(destination, rel)));
  const keep = list.keep.filter((rel) => fs.existsSync(path.join(destination, rel)));
  return { tests, hookFiles, keep };
}

function move(from, to) {
  ensureDir(path.dirname(to));
  fs.rmSync(to, { recursive: true, force: true });
  fs.renameSync(from, to);
}

/** Put back a stash left by an interrupted run. */
function recoverStash(destination, log) {
  const stash = path.join(destination, STASH);
  if (!isDirectory(stash)) return;
  log(`  warning: ${STASH}/ found (an interrupted run); restoring it first`);
  restore(destination, log);
}

/** Set the protected paths aside. Returns the record of what was stashed. */
function stash(destination, log = console.log) {
  recoverStash(destination, log);
  const list = loadList(destination, log);
  const hasHookFiles =
    isDirectory(path.join(destination, PLATFORMS)) &&
    fs.readdirSync(path.join(destination, PLATFORMS)).some((p) => isFile(path.join(destination, PLATFORMS, p, 'tests', HOOK_FILE)));
  if (!list && !hasHookFiles) return null;
  const effective = list ?? { tests: [], keep: [] };
  const found = protectedPaths(destination, effective);
  for (const test of found.tests) {
    if (!test.paths.length) log(`  warning: local test ${test.name}: no folder in this workspace; nothing to keep`);
  }
  const entries = [...found.tests.flatMap((t) => t.paths), ...found.hookFiles, ...found.keep];
  const stashDir = path.join(destination, STASH);
  ensureDir(stashDir);
  const moved = [];
  entries.forEach((rel, index) => {
    const target = path.join(stashDir, String(index));
    move(path.join(destination, rel), target);
    moved.push({ rel, stashed: String(index) });
  });
  writeJson(path.join(stashDir, 'stash.json'), { moved });
  if (moved.length) log(`  local: set aside ${moved.length} path(s) (${LIST})`);
  return { list: effective, found };
}

/** Move the stash back over whatever the copy put there; the local copy wins. */
function restore(destination, log = console.log) {
  const stashDir = path.join(destination, STASH);
  if (!isDirectory(stashDir)) return [];
  const { moved = [] } = readJson(path.join(stashDir, 'stash.json'), {});
  for (const item of moved) {
    const from = path.join(stashDir, item.stashed);
    if (fs.existsSync(from)) move(from, path.join(destination, item.rel));
  }
  fs.rmSync(stashDir, { recursive: true, force: true });
  if (moved.length) log(`  local: restored ${moved.length} path(s)`);
  return moved.map((m) => m.rel);
}

// -----------------------------------------------------------------------------
// The hooks

/** The builder's hooks and their default bodies, read from board-tests/CMakeLists.txt. */
function builderHooks(testsDir) {
  const text = read(path.join(testsDir, 'board-tests', 'CMakeLists.txt'));
  const hooks = new Map();
  for (const match of text.matchAll(/^function\s*\(\s*(board_test_\w+)\s+_app\s+_out\s*\)\n([\s\S]*?)^endfunction\s*\(\s*\)/gm)) {
    hooks.set(match[1], match[2]);
  }
  return hooks;
}

function dispatch(hook, indent = '  ') {
  return [
    `${indent}# local tests (${MARK}): ${HOOK_FILE} may answer first.`,
    `${indent}if (COMMAND ${hook}_local)`,
    `${indent}  set (_local_out "")`,
    `${indent}  ${hook}_local ("\${_app}" _local_out)`,
    `${indent}  if (NOT "\${_local_out}" STREQUAL "")`,
    `${indent}    set (\${_out} \${_local_out} PARENT_SCOPE)`,
    `${indent}    return ()`,
    `${indent}  endif ()`,
    `${indent}endif ()`,
  ].join('\n');
}

/**
 * Give every hook of a platform's tests.cmake a *_local twin: a dispatch at
 * the top of the hooks it defines, and wrappers of the builder's defaults
 * for the others. Generated whether or not tests.local.cmake exists.
 */
function patchHooks(testsDir, platformId) {
  const testDir = path.join(testsDir, 'platforms', platformId, 'tests');
  const file = path.join(testDir, 'tests.cmake');
  let text = read(file);
  if (text.includes(MARK)) return false;
  const hooks = builderHooks(testsDir);
  if (!hooks.size) return false;
  const defined = new Set();
  for (const hook of hooks.keys()) {
    const pattern = new RegExp(`(^function\\s*\\(\\s*${hook}\\s+_app\\s+_out\\s*\\)[^\\n]*\\n)`, 'gm');
    if (pattern.test(text)) {
      defined.add(hook);
      text = text.replace(pattern, `$1${dispatch(hook)}\n`);
    }
  }
  const block = [
    '',
    `# ---- local tests (${MARK}) ---------------------------------------`,
    `# A user-owned ${HOOK_FILE} next to this file holds the CMake wiring of the`,
    '# tests listed in scripts/local-tests.txt (at the workspace root): any',
    '# board_test_<hook>_local (_app _out) answers first for the tests it sets',
    '# ${_out} for. It may also append to the lists (BOARD_TEST_HWD_ONLY, ...).',
    '# A re-scaffold keeps it.',
    `include ("\${CMAKE_CURRENT_LIST_DIR}/${HOOK_FILE}" OPTIONAL)`,
    '',
    "# The hooks this file does not define consult the local twins too, then",
    "# give the builder's default answer.",
  ];
  for (const [hook, body] of hooks) {
    if (defined.has(hook)) continue;
    block.push(`function (${hook} _app _out)`, dispatch(hook), body.replace(/\n$/, ''), 'endfunction ()');
  }
  block.push('');
  writeFile(file, `${text}${block.join('\n')}\n`);
  return true;
}

/**
 * A local test that shares its name with a shared test (tests/sources/) of
 * its platform replaces it: drop the name from the platform's UOS_TESTS_*
 * lists, or the builder stops ("both a portable test and a board test").
 */
function preferLocal(testsDir, platformId, names, filterCmakeList) {
  const file = path.join(testsDir, 'platforms', platformId, 'CMakeLists.txt');
  let text = read(file);
  const original = text;
  for (const list of ['UOS_TESTS_SOURCES', 'UOS_TESTS_PORTABLE', 'UOS_TESTS_STORAGE', 'UOS_TESTS_SUITES']) {
    const match = new RegExp(`set\\s*\\(\\s*${list}\\b([^)]*)\\)`, 'm').exec(text);
    if (!match) continue;
    const words = match[1].split(/\s+/).filter(Boolean);
    text = filterCmakeList(text, list, new Set(words.filter((w) => !names.includes(w))));
  }
  if (text !== original) writeFile(file, text);
  return text !== original;
}

module.exports = { LIST, STASH, MARK, HOOK_FILE, parseList, loadList, stash, restore, patchHooks, preferLocal };

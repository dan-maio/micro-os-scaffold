function integrationReadme(config) {
  const ports = (config.projects ?? []).filter(
    (project) => project.role !== 'kernel' && (config.selectedProjects ?? []).includes(project.id)
  );
  return `# Source-level integration

Each subdirectory is a minimal, standalone CMake entry point that assembles the kernel and one port
through \`add_subdirectory()\`. They are separate because the ports target different architectures and
cannot share one toolchain.

- the kernel exports \`micro-os-plus::iii\` (and \`micro-os-plus::iii-core\`);
- each port exports an INTERFACE target whose sources and include directories are compiled into the consumer;
- no port is built as a pre-built library, and no install step is required.

Selected ports:

${ports.map((project) => `- \`${project.scaffoldName}/CMakeLists.txt\` → \`micro-os-plus::${project.architecture}\``).join('\n') || '- (none)'}

## Configure

Use the toolchain of the target platform. From the destination root:

\`\`\`bash
source tests/scripts/env.sh

# AArch32 / Cortex-M
cmake -S integration/micro-os-plus-iii-cortexm -B build/integration-cortexm -G Ninja \\
  -D CMAKE_TOOLCHAIN_FILE="$UOS_TOOLCHAIN_FILE_ARM"
cmake --build build/integration-cortexm

# AArch64
cmake -S integration/micro-os-plus-iii-aarch64 -B build/integration-aarch64 -G Ninja \\
  -D CMAKE_TOOLCHAIN_FILE="$UOS_TOOLCHAIN_FILE_AARCH64"

# POSIX host
cmake -S integration/micro-os-plus-iii-posix-arch -B build/integration-native -G Ninja \\
  -D CMAKE_C_COMPILER="$UOS_TOOL_GCC" -D CMAKE_CXX_COMPILER="$UOS_TOOL_G__"
\`\`\`

The build and test path used by the scaffolder is \`tests/\` (the CTest harness), not this directory.
`;
}


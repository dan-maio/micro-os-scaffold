'use strict';

const path = require('node:path');
const { extensionGuide, workedExample } = require('./extension-guide');

function code(value) {
  return `\`${value}\``;
}

function table(headers, rows) {
  const lines = [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
  ];
  for (const row of rows) lines.push(`| ${row.join(' | ')} |`);
  return lines.join('\n');
}

function shortGit(project) {
  if (!project.git) return 'not a git working copy';
  const dirty = project.git.dirty ? ' (dirty)' : '';
  return `${code(project.git.branch || 'detached')} @ ${code(project.git.commit)}${dirty}`;
}

function toolRows(config, keys) {
  const rows = [];
  for (const key of keys) {
    const tool = config.tools?.[key];
    if (!tool) continue;
    rows.push([
      code(key),
      tool.found ? code(tool.version ?? '?') : '**MISSING**',
      tool.found ? code(tool.path) : '—',
      tool.found ? tool.origin : 'not found',
    ]);
  }
  return rows;
}

function libraryRows(config, keys) {
  const rows = [];
  for (const key of keys) {
    const library = config.libraries?.[key];
    if (!library) continue;
    rows.push([
      code(key),
      library.found ? code(library.version ?? '?') : '**MISSING**',
      library.found ? code(library.path) : '—',
    ]);
  }
  return rows;
}

function buildResultRows(config) {
  const results = config.build?.results ?? [];
  if (!results.length) return null;
  return results.map((result) => [
    code(result.name),
    result.project ?? '—',
    result.platform ?? '—',
    result.status === 'pass' ? '**PASS**' : result.status === 'fail' ? '**FAIL**' : result.status,
    result.configure?.exitCode ?? '—',
    result.build?.exitCode ?? '—',
    result.logDir ? code(result.logDir) : '—',
  ]);
}


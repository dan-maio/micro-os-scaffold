function probeSummary(project) {
  const boards = project.boards ?? [];
  if (!boards.length) return 'No board directory was found for this project.';
  const rows = boards.map((board) => [
    code(board.id),
    board.adapter ?? (board.hardwareRunner ? 'OpenOCD (adapter from openocd.cfg)' : '—'),
    board.transport ?? '—',
    board.vidPid ? code(board.vidPid) : '—',
    board.gdbServer ?? '—',
    board.openocdConfig ? code(`test/boards/${board.id}/openocd.cfg`) : '—',
  ]);
  return table(['Board', 'Adapter', 'Transport', 'VID:PID', 'GDB server', 'OpenOCD config'], rows);
}

function preTestNotes(project) {
  const boards = (project.boards ?? []).filter((board) => board.preTestScript);
  if (!boards.length) return '';
  const lines = [];
  lines.push('### Hardware preparation');
  lines.push('');
  lines.push(
    'Before `-hwd` tests on these boards, the board must be put into the state the ' +
      'hardware runner expects. The generated board `hw.sh` now runs the preparation ' +
      'script automatically (set `UOS_SKIP_PRE_TEST=1` to skip it):'
  );
  lines.push('');
  for (const board of boards) {
    const relative = path.relative(project.sourcePath, board.preTestScript);
    lines.push(`- ${code(board.id)}: ${code(relative)}`);
  }
  lines.push('');
  lines.push(
    'For the VisionFive 2 Lite this resets the SoC and interrupts the U-Boot ' +
      'autoboot countdown so the board stays at the U-Boot prompt; the test is then ' +
      'loaded into DDR, not flash or the SD card. The reset script needs the probe ' +
      'UART / a serial device and OpenOCD, and takes about 10-15 seconds.'
  );
  lines.push('');
  lines.push('Manual preparation is also available:');
  lines.push('');
  lines.push('```bash');
  for (const board of boards) {
    lines.push(`tests/scripts/prepare-${board.id}.sh`);
  }
  lines.push('```');
  lines.push('');
  return lines.join('\n');
}

function projectBuildConfigs(config, project) {
  const nonCmake = project.buildSystem && project.buildSystem !== 'cmake';
  const configs = nonCmake
    ? (config.build?.configurations ?? []).filter(
        (entry) => entry.project === project.id
      )
    : (config.harness?.buildConfigurations ?? []).filter((entry) =>
        (project.platforms ?? []).some((platform) => platform.id === entry.platform)
      );
  const selectedPlatforms = new Set(
    (config.selections ?? [])
      .filter((selection) => selection.projectId === project.id)
      .map((selection) => selection.platformId)
  );
  const rows = configs.map((entry) => [
    code(entry.name),
    code(entry.platform),
    entry.buildType,
    entry.name === project.defaultBuildConfiguration ? 'yes' : '',
    selectedPlatforms.has(entry.platform) ? '**yes**' : '',
  ]);
  if (!rows.length) return 'No build configuration was discovered for this project.';
  return table(['Configuration', 'Platform', 'Build type', 'Default', 'Selected'], rows);
}


